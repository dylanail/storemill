 await t.test('provider failures remain failures, cancel prevents execution, and undo protects newer edits', async () => {
  const f = fixture()
  useMediaTransport(async () => new Response('failed', { status: 429 }))
  const job = startRebrand(db, f.store.id, user.id, f.source, { method: 'ai', provider: 'openai' })
  await drainRebrands(db); const failed = getRebrand(db, f.store.id, job.id)
  assert.equal(failed.status, 'failed'); assert.match(failed.error, /429/); assert.equal(failed.result_url, '')
  assert.throws(() => applyRebrand(db, f.store.id, user.id, job.id, ''), /completed preview/)
  useMediaTransport(null)
  const cancelled = startRebrand(db, f.store.id, user.id, f.source, { method: 'overlay', logo: f.logo })
  await cancelRebrand(db, f.store.id, user.id, cancelled.id); await drainRebrands(db)
  assert.equal(getRebrand(db, f.store.id, cancelled.id).status, 'cancelled')
  const newer = startRebrand(db, f.store.id, user.id, f.source, { method: 'overlay', logo: f.logo }); await drainRebrands(db)
  const ready = getRebrand(db, f.store.id, newer.id)
  applyRebrand(db, f.store.id, user.id, newer.id, changesToken(rebrandChanges(db, f.store.id, f.source, ready.result_url)))
  db.run('UPDATE products SET hero_image=? WHERE id=?', '/newer-merchant-edit.png', f.product.id)
  assert.throws(() => undoRebrand(db, f.store.id, user.id, newer.id), /edited after/)
  assert.equal(db.one<{ hero_image: string }>('SELECT hero_image FROM products WHERE id=?', f.product.id)!.hero_image, '/newer-merchant-edit.png')
 })
