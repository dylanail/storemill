 await t.test('actual image overlay preserves dimensions and places the exact logo; apply and undo stay in this store', async () => {
  const f = fixture(), other = fixture()
  const options = { method: 'overlay' as const, logo: f.logo, brandName: 'My new brand' }
  const job = startRebrand(db, f.store.id, user.id, f.source, options)
  assert.equal(startRebrand(db, f.store.id, user.id, f.source, options).id, job.id)
  await drainRebrands(db)
  const ready = getRebrand(db, f.store.id, job.id)
  assert.equal(ready.status, 'review', ready.error)
  const output = readUpload(ready.result_url)!; writeFileSync(join(dir, 'rendered.png'), output.data)
  const sample = run(['-i', join(dir, 'rendered.png'), '-vf', 'crop=1:1:580:330,format=rgb24', '-f', 'rawvideo', 'pipe:1'])
  assert.ok(sample[0]! > 230 && sample[2]! < 20, `Logo pixel ${sample.toString('hex')}`)
  const before = db.one<{ raw_html: string }>('SELECT raw_html FROM pages WHERE id=?', f.page.id)!.raw_html
  const changes = rebrandChanges(db, f.store.id, f.source, ready.result_url)
  assert.ok(changes.length >= 2)
  assert.throws(() => applyRebrand(db, f.store.id, user.id, job.id, 'stale'), /changed since/)
  applyRebrand(db, f.store.id, user.id, job.id, changesToken(changes))
  assert.match(db.one<{ raw_html: string }>('SELECT raw_html FROM pages WHERE id=?', f.page.id)!.raw_html, new RegExp(ready.result_url))
  assert.equal(db.one<{ hero_image: string }>('SELECT hero_image FROM products WHERE id=?', other.product.id)!.hero_image, other.source)
  assert.ok(db.one<{ n: number }>('SELECT COUNT(*) n FROM page_revisions WHERE page_id=?', f.page.id)!.n >= 3)
  undoRebrand(db, f.store.id, user.id, job.id)
  assert.equal(db.one<{ raw_html: string }>('SELECT raw_html FROM pages WHERE id=?', f.page.id)!.raw_html, before)
  assert.deepEqual(readUpload(f.source)!.data, png)
 })
